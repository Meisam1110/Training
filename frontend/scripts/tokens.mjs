// Turns docs/design-tokens.json (the single source) into CSS variables + resolved themes.
// Status colours are AUTO-ADJUSTED per theme until they meet WCAG AA (4.5:1) on both their
// tinted chip background and the surface, so the JSON stays untouched and swappable.

const hex = (h) => { h = h.replace("#", ""); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)); };
const toHex = (rgb) => "#" + rgb.map((v) => Math.round(Math.min(255, Math.max(0, v))).toString(16).padStart(2, "0")).join("").toUpperCase();
const lin = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; };
const lum = (h) => { const [r, g, b] = hex(h); return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b); };

export function contrast(a, b) {
  const [l1, l2] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
}
/** mix(a,b,p): p percent of a, rest b (sRGB, same as CSS color-mix in srgb). */
export function mix(a, b, p) {
  const A = hex(a), B = hex(b);
  return toHex(A.map((v, i) => (v * p) / 100 + B[i] * (1 - p / 100)));
}

/** Push `fg` towards `toward` until it has >= min contrast on every background. */
function ensure(fg, bgsFn, toward, min) {
  let p = 100, c = fg;
  for (;;) {
    const bgs = bgsFn(c);
    if (bgs.every((b) => contrast(c, b) >= min) || p <= 0) return c;
    p -= 2; c = mix(fg, toward, p);
  }
}

function resolveTheme(t, isDark) {
  const c = t.color;
  const base = isDark ? { ...c, ...c.dark } : c;
  const toward = isDark ? "#FFFFFF" : "#000000";
  const out = {
    bg: base.bg, surface: base.surface, line: base.line, text: base.text, "text-muted": base.textMuted,
    brand: c.brand, "brand-ink": c.brandInk, "brand-deep": c.brandDeep,
  };
  // Subtle raised surface and strong line derived from the given neutrals.
  out["surface-2"] = mix(base.text, base.surface, 4);
  out["line-strong"] = ensure(mix(base.text, base.surface, isDark ? 38 : 45), () => [base.surface, base.bg], base.text, 3);
  for (const k of ["ok", "warn", "danger", "info"]) {
    const bgOf = (fg) => mix(fg, base.surface, isDark ? 20 : 12);
    const fg = ensure(base[k], (x) => [bgOf(x), base.surface, base.bg], toward, t.a11y.minContrastText);
    out[k] = fg; out[`${k}-bg`] = bgOf(fg);
  }
  const ringBase = t.a11y.focusRing.match(/#[0-9a-fA-F]{6}/)?.[0] ?? c.info;
  out["focus-ring"] = ensure(ringBase, () => [base.bg, base.surface], toward, 3);
  out["on-brand"] = c.brandInk;
  out["overlay"] = isDark ? "rgba(0,0,0,.62)" : "rgba(26,26,26,.45)";
  return out;
}

const decl = (o) => Object.entries(o).map(([k, v]) => `  --${k}: ${v};`).join("\n");

export function buildTokens(t) {
  const light = resolveTheme(t, false), dark = resolveTheme(t, true);
  const sp = t.space.map((v, i) => `  --space-${i + 1}: ${v}px;`).join("\n");
  const fs = t.font.scale.map((v, i) => `  --fs-${i + 1}: ${v / t.font.base}rem;`).join("\n");
  const shared = `${sp}
${fs}
  --font-family: ${t.font.family};
  --font-base: ${t.font.base}px;
  --radius-sm: ${t.radius.sm}px;
  --radius-md: ${t.radius.md}px;
  --radius-lg: ${t.radius.lg}px;
  --sidebar-width: ${t.layout.sidebarWidth}px;
  --min-touch: ${t.layout.minTouch}px;
  --max-content: ${t.layout.maxContent}px;
  --focus-ring-width: 2px;`;
  const css = `/* GENERATED by scripts/gen-tokens.mjs from docs/design-tokens.json — do not edit. */
:root {
  color-scheme: light;
${shared}
${decl(light)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${decl(dark).replace(/^/gm, "  ")}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${decl(dark)}
}
`;
  return { css, light, dark };
}
